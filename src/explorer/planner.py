"""
ExplorationPlanner — LangGraph sub-graph (Sprint 5 / Task 3).

Input:  start_url, sfg_store, existing_skills
Output: list[TestHypothesis]

Graph:
  START → crawl → cluster → gap_analysis → hypothesis → judge → END
  judge routes back to hypothesis on approved=False (max 2 retries)
"""
from __future__ import annotations

from typing import TypedDict

import numpy as np
from loguru import logger
from langgraph.graph import StateGraph, START, END
from pydantic import BaseModel, ConfigDict, Field

from src.config_loader import get_exploration_config
from src.contractskill.compiler import ContractSkill
from src.contractskill.crawler import SFGCrawler, CrawlerConfig
from src.contractskill.sfg import SFGNode, SFGStore
from src.explorer.hypothesis import TestHypothesis
from src.llm.adapter import DEFAULT_MODEL, OllamaAdapter, _inference_semaphore
